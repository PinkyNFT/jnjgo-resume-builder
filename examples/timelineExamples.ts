/**
 * Complete example showing how to prepare data for ResumeEditor
 */
export function getCompleteTimelineData() {
    // 1. Get employer timeline
    const employerTimeline = getEmployerTimelineFromWork(exampleWorkExperience);

    // 2. Generate skill timelines automatically
    const autoSkills = generateSkillTimelinesFromWork(exampleWorkExperience);

    // 3. Add manual skill timelines
    const manualSkills = [
        createSkillTimeline('Strategic Planning', 2012, null, 'Deloitte'),
        createSkillTimeline('Client Management', 2014, null, 'Multiple firms')
    ];

    // 4. Combine and merge
    const allSkills = mergeSkillTimelines([...autoSkills, ...manualSkills]);

    // 5. Convert to chart items
    const skillTimeline = getSkillTimelineFromSkills(allSkills);

    return {
        employerTimeline,
        skillTimeline,
        skillTimelineData: allSkills
    };
}


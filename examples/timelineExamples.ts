/**
 * Convert work experience to employer timeline items
 */
export function getEmployerTimelineFromWork(work: WorkExperience[]): TimelineChartItem[] {
    return work
        .map(w => {
            const parsed = parsePeriod(w.period);
            if (!parsed) return null;
            return {
                id: w.id,
                label: w.company,
                startYear: parsed.startYear,
                endYear: parsed.endYear
            };
        })
        .filter((item): item is TimelineChartItem => item !== null);
}


/**
 * Validate example data
 */
export function validateExamples() {
    const results = {
        employerTimeline: {
            count: exampleWorkExperience.length,
            parsed: 0,
            failed: 0
        },
        skillTimeline: {
            count: exampleSkillTimelines.length,
            parsed: 0,
            failed: 0
        }
    };

    // Validate employer timeline
    for (const work of exampleWorkExperience) {
        const parsed = parsePeriod(work.period);
        if (parsed) {
            results.employerTimeline.parsed++;
        } else {
            results.employerTimeline.failed++;
            console.error(`Failed to parse period: ${work.period} for ${work.company}`);
        }
    }

    // Validate skill timeline
    for (const skill of exampleSkillTimelines) {
        const parsed = parsePeriod(skill.period);
        if (parsed) {
            results.skillTimeline.parsed++;
        } else {
            results.skillTimeline.failed++;
            console.error(`Failed to parse period: ${skill.period} for ${skill.skillName}`);
        }
    }

    console.log('Validation Results:', results);
    return results;
}

